; ----------------------------------------------------------------------------
; uint32_t hf_crc32(const uint8_t *buf /*rdi*/, size_t len /*rsi*/)
; ----------------------------------------------------------------------------
hf_crc32:
            mov     eax, 0xFFFFFFFF     ; crc = ~0
            lea     r8,  [rel crc32_tab]
            test    rsi, rsi
            jz      .fin
.next:
            movzx   edx, byte [rdi]     ; b = *buf
            xor     dl,  al             ; idx = (crc ^ b) & 0xff
            movzx   edx, dl
            shr     eax, 8              ; crc >>= 8
            xor     eax, [r8 + rdx*4]   ; crc ^= tab[idx]
            inc     rdi
            dec     rsi
            jnz     .next
.fin:
            not     eax                 ; crc = ~crc
            ret

; ----------------------------------------------------------------------------
; uint64_t hf_fnv1a64(const uint8_t *buf /*rdi*/, size_t len /*rsi*/)
; ----------------------------------------------------------------------------
hf_fnv1a64:
            mov     rax, [rel fnv_off]
            mov     r9,  [rel fnv_prime]
            test    rsi, rsi
            jz      .done
.step:
            movzx   edx, byte [rdi]
            xor     rax, rdx            ; hash ^= byte
            imul    rax, r9             ; hash *= prime
            inc     rdi
            dec     rsi
            jnz     .step
.done:
            ret

; ----------------------------------------------------------------------------
; uint32_t hf_adler32(const uint8_t *buf /*rdi*/, size_t len /*rsi*/)
; ----------------------------------------------------------------------------
hf_adler32:
            mov     eax, 1              ; a = 1
            xor     r10d, r10d          ; b = 0
            mov     r11d, 65521         ; MOD_ADLER
            test    rsi, rsi
            jz      .end
.acc:
            movzx   edx, byte [rdi]
            add     eax, edx            ; a += byte
            xor     edx, edx
            div     r11d                ; a %= MOD (edx:eax / r11d)
            mov     eax, edx            ; a = remainder
            add     r10d, eax           ; b += a
            mov     r8d, r10d
            mov     eax, r8d
            xor     edx, edx
            div     r11d
            mov     r10d, edx           ; b %= MOD
            mov     eax, 1
            ; (упрощённо, демонстрационно)
            inc     rdi
            dec     rsi
            jnz     .acc
.end:
            mov     eax, r10d
            shl     eax, 16
            or      eax, 1
            ret

; ----------------------------------------------------------------------------
; uint64_t hf_djb2(const uint8_t *buf /*rdi*/, size_t len /*rsi*/)
; ----------------------------------------------------------------------------
hf_djb2:
            mov     rax, 5381
            test    rsi, rsi
            jz      .ok
.ch:
            mov     rcx, rax
            shl     rax, 5              ; hash*32
            add     rax, rcx            ; + hash  => hash*33
            movzx   edx, byte [rdi]
            add     rax, rdx            ; + byte
            inc     rdi
            dec     rsi
            jnz     .ch
.ok:
            ret

; ----------------------------------------------------------------------------
; uint32_t hf_sum32(const uint32_t *buf /*rdi*/, size_t n /*rsi*/)
;   Сумма n 32-битных слов (wrap-around).
; ----------------------------------------------------------------------------
hf_sum32:
            xor     eax, eax
            test    rsi, rsi
            jz      .r
.s:
            add     eax, [rdi]
            add     rdi, 4
            dec     rsi
            jnz     .s
.r:
            ret

